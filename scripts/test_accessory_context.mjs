import assert from "node:assert/strict";
import fs from "node:fs";
import {REFERENCE_PRODUCTS} from "../assets/product-room-research.mjs";
import {firearmContext,reviewAccessoryContext,suggestedAccessories} from "../assets/accessory-context.mjs";
import {evaluatePairing} from "../assets/pairing-evidence.mjs";
const item=id=>REFERENCE_PRODUCTS.find(x=>x.id===id);
const precision=item("ruger-precision-308-gen1"),pistol=item("glock-g19-gen5-mos");
const scope=item("meopta-optika6-3-18x56-rd-sfp"),pistolOptic=item("holosun-scs-m-gr"),holster=item("aliengear-photon"),light=item("streamlight-tlr7-x");
assert.equal(firearmContext(precision).id,"precision-rifle");
assert.equal(firearmContext(item("ruger-precision")).id,"precision-rifle");
assert.equal(firearmContext(item("ruger-american-gen2")).id,"rifle");
assert.equal(firearmContext(pistol).id,"pistol");
assert.equal(firearmContext(item("beretta-a300-patrol")).id,"shotgun");
assert.equal(reviewAccessoryContext(precision,holster).tier,"not-applicable","A rifle must never recommend handgun holsters");
assert.equal(reviewAccessoryContext(precision,pistolOptic).tier,"not-suggested","Pistol MOS sights must not be promoted as default precision-rifle optics");
assert.equal(reviewAccessoryContext(precision,light).tier,"not-suggested","Pistol lights are not generic rifle recommendations");
assert.equal(reviewAccessoryContext(precision,scope).tier,"explore","Magnified rifle scope is a sensible category to explore");
assert.equal(reviewAccessoryContext(pistol,scope).tier,"not-suggested","A full-size rifle scope is not a default handgun accessory");
assert.equal(reviewAccessoryContext(pistol,holster).tier,"explore","Holster type may be relevant, but shell fit is unknown");
assert.equal(reviewAccessoryContext(pistol,pistolOptic).tier,"explore");
assert.equal(reviewAccessoryContext(item("beretta-a300-patrol"),holster).tier,"not-applicable");
assert.equal(reviewAccessoryContext(item("beretta-a300-patrol"),pistolOptic).tier,"review");
assert.deepEqual(suggestedAccessories(precision,REFERENCE_PRODUCTS.filter(x=>x.kind==="accessory")).map(x=>x.id),[scope.id],"Precision rifle demo should suggest rifle scope rather than pistol products");
assert.equal(suggestedAccessories(item("beretta-a300-patrol"),REFERENCE_PRODUCTS).length,0,"No invented shotgun-specific pairing recommendations");
assert.equal(reviewAccessoryContext(precision,{...scope,approvedItem:{id:"approved"}}).tier,"review","Published catalog record isn't enough for recommendation");
assert.equal(evaluatePairing(pistol,pistolOptic).status,"manufacturer-listed","Exact evidence remains distinct from usage guidance");
assert.equal(evaluatePairing(precision,scope).status,"not-reviewed","Never fabricate exact Ruger/Meopta mounting fit");
const html=fs.readFileSync(new URL("../product-room.html",import.meta.url),"utf8");
const js=fs.readFileSync(new URL("../assets/product-room.js",import.meta.url),"utf8");
for(const id of ["accessory-context","accessory-mode","accessory-show-all","intel-context"])
 assert.ok(html.includes('id="'+id+'"'),"Missing context UI "+id);
assert.match(js,/suggestedAccessories\(current,items\)/);
assert.match(js,/reviewAccessoryContext\(current,accessory\)/);
assert.match(js,/\$\("accessory-show-all"\)\.addEventListener\("change",refreshAccessoryContext\)/);
assert.match(js,/\$\("theater-try-meopta"\)\.hidden=/);
assert.match(js,/btn\.hidden=reviewAccessoryContext\(item,candidate\)/);
assert.doesNotMatch(html,/Discover a manufacturer-listed pairing:/,"Rifle-plus-scope photo example must not imply manufacturer-listed pairing");
console.log("Context-aware firearm guidance: pistol holster and compact red-dot exclusions for precision rifles, separate fit evidence, opt-in broad browse verified.");
