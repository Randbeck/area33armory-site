import assert from "node:assert/strict";
import fs from "node:fs";
import {REFERENCE_PRODUCTS} from "../assets/product-room-research.mjs";
import {OPEN_LICENSE_MEDIA,researchPhotoFor} from "../assets/research-photo-license.mjs";
import {clampPhotoZoom,clampPhotoPan} from "../assets/research-photo-viewer.mjs";
const html=fs.readFileSync(new URL("../product-room.html",import.meta.url),"utf8");
const code=fs.readFileSync(new URL("../assets/product-room.js",import.meta.url),"utf8");
const style=fs.readFileSync(new URL("../assets/product-room.css",import.meta.url),"utf8");
const home=fs.readFileSync(new URL("../index.html",import.meta.url),"utf8");
assert.equal(OPEN_LICENSE_MEDIA.length,3,"Research photo imports must be individually documented");
const media=OPEN_LICENSE_MEDIA.find(x=>x.productId==="ruger-precision-308-gen1");
const exact=REFERENCE_PRODUCTS.find(x=>x.id==="ruger-precision-308-gen1");
assert.ok(exact);
assert.equal(researchPhotoFor(exact),media);
assert.equal(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="ruger-precision")),null,"No family-level photograph substitution");
assert.equal(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="glock-g19-gen5")),null);
assert.equal(researchPhotoFor({...exact,approvedItem:{id:"catalog_deadbeef"}}),null,"Never override owner-approved media with research photo");
assert.equal(researchPhotoFor({...exact,kind:"accessory"}),null,"No wrong-kind image substitution");
assert.equal(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="ruger-precision-6mm-2019-photo")).author,"Tactical Accountants");
assert.equal(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="meopta-optika6-3-18x56-rd-sfp")).author,"Microflexer");
assert.equal(researchPhotoFor({...exact,id:"meopta-optika6-3-18x56-rd-sfp"}),null,"An id change cannot attach an accessory photo to a firearm object");
assert.equal(media.author,"Coati077");
assert.equal(media.license,"CC BY-SA 4.0");
assert.equal(media.src,"https://upload.wikimedia.org/wikipedia/commons/b/ba/Ruger_Precision_Rifle_308_Gen_1.jpg");
assert.equal(new URL(media.sourcePage).hostname,"commons.wikimedia.org");
assert.equal(new URL(media.licenseUrl).hostname,"creativecommons.org");
assert.match(media.caption,/\.308 Winchester, Generation 1/);
assert.match(media.modifications,/unmodified/i);
assert.equal(clampPhotoZoom(-7),1);
assert.equal(clampPhotoZoom(30),3.5);
assert.equal(clampPhotoZoom(NaN),1);
assert.equal(clampPhotoZoom(1.5),1.5);
assert.deepEqual(clampPhotoPan({x:700,y:-700},100,200,2),{x:50,y:-100});
assert.deepEqual(clampPhotoPan({x:100,y:50},100,200,1),{x:0,y:0});
