#!/usr/bin/env python3
"""Refresh approved Area 33 catalog privately without reapproving unchanged SKUs.

Carries forward EXACT previously approved public records and verified image
bytes. Applies only new, independently fully approved owner-review bundles.
Any removal requires a separately reviewed withdrawal record. Rights holds
apply to ALL retained and added records. No distributor feed, private draft,
live stock/price or site deployment is read or performed.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import secrets
import shutil
import tempfile

from catalog_release_safety import read_rights_holds, reject_held_products
from prepare_approved_catalog_shards import (
    PER_SHARD, MAX_PRODUCTS, RELEASE_SCHEMA, SHARD_SCHEMA,
    _private_destination, _withdrawals, _encode, gather_approved,
)
from stage_private_media_withdrawal import _approved_previous

IMAGE = re.compile(r"^assets/approved/catalog/(catalog_[a-f0-9]{20})/view-0[1-8]\.jpg$")


class CatalogRefreshError(ValueError):
    pass


def _content_changed(old: dict, new: dict) -> bool:
    # Publication timestamp is generated by the publisher; it is not an
    # identity or content change. Preserve old timestamp for unchanged rows.
    keys = set(old) | set(new)
    return any(old.get(k) != new.get(k) for k in keys if k != "publication_updated_at")


def refresh_approved_catalog(
    previous_private_release: Path, output: Path, *,
    rights_holds_file: Path, approved_bundles: list[Path] | None = None,
    reviewed_withdrawals: Path | None = None,
):
    previous_private_release = Path(previous_private_release).expanduser().resolve()
    output = _private_destination(Path(output))
    if (output.is_relative_to(previous_private_release) or
            previous_private_release.is_relative_to(output)):
        raise CatalogRefreshError("Refresh output cannot nest within prior release")
    prior_index, old_products, old_provenance, old_images = _approved_previous(
        previous_private_release
    )
    holds = read_rights_holds(rights_holds_file)
    old_by_id = {x["id"]: x for x in old_products}
    withdraw = _withdrawals(reviewed_withdrawals)
    if set(withdraw) - set(old_by_id):
        raise CatalogRefreshError("Withdrawals must name previously approved catalog IDs")

    bundles = approved_bundles or []
    if bundles:
        newly_approved, new_frames, new_provenance = gather_approved(bundles)
    else:
        newly_approved, new_frames, new_provenance = [], [], []
    new_by_id = {p["id"]: p for p in newly_approved}
    new_prov_by_id = {p["id"]: p for p in new_provenance}
    if set(withdraw) & set(new_by_id):
        raise CatalogRefreshError("A withdrawn item cannot be re-added in the same refresh")

    # Manufacturer/model/variant/type are identity; do not silently overwrite
    # one product with another under its original opaque public ID.
    identity_keys = ("manufacturer", "model", "variant", "category", "product_type")
    for ident in set(old_by_id) & set(new_by_id):
        if any(old_by_id[ident][k] != new_by_id[ident][k] for k in identity_keys):
            raise CatalogRefreshError("Changed exact product identity requires a new ID and withdrawal")

    products = {ident: data for ident, data in old_by_id.items() if ident not in withdraw}
    provenance = {ident: data for ident, data in old_provenance.items() if ident not in withdraw}
    photos = {
        url: path for url, path in old_images.items()
        if IMAGE.fullmatch(url).group(1) not in withdraw
    }
    previously_approved_unchanged = 0
    independently_reapproved_changed = 0
    added = 0
    refreshed_unchanged = 0
    new_sources = {
        frame["public"]["url"]: Path(frame["source"])
        for frame in new_frames
    }
    if len(new_sources) != len(new_frames):
        raise CatalogRefreshError("Newly approved media has duplicate public paths")
    for ident, new_record in new_by_id.items():
        if ident not in old_by_id:
            added += 1
            products[ident] = new_record
            provenance[ident] = new_prov_by_id[ident]
        elif _content_changed(old_by_id[ident], new_record):
            independently_reapproved_changed += 1
            products[ident] = new_record
            provenance[ident] = new_prov_by_id[ident]
        else:
            refreshed_unchanged += 1
            continue
    if len(products) > MAX_PRODUCTS:
        raise CatalogRefreshError("Refresh exceeds approved-only record cap")
    previously_approved_unchanged = sum(
        ident in old_by_id and products[ident] == old_by_id[ident]
        for ident in products
    )
    # Retain only images referenced by the FINAL product records; verify source
    # bytes exactly, and reject changing an image at an existing immutable URL.
    required_images = {}
    for ident, item in products.items():
        images = provenance[ident]["images"]
        if len(images) != len(item["images"]):
            raise CatalogRefreshError("Final record image provenance does not match")
        for media in images:
            url, expected = media["public_url"], media["original_sha256"]
            match = IMAGE.fullmatch(url)
            if not match or match.group(1) != ident:
                raise CatalogRefreshError("Approved image path has an unsafe product association")
            if url in photos and url in new_sources:
                old_hash = hashlib.sha256(photos[url].read_bytes()).hexdigest()
                new_hash = hashlib.sha256(new_sources[url].read_bytes()).hexdigest()
                if old_hash != new_hash:
                    raise CatalogRefreshError(
                        "Cannot replace media bytes at a previously approved URL; "
                        "use a new reviewed product ID and explicit withdrawal"
                    )
            src = new_sources.get(url) if ident in new_by_id and (
                ident not in old_by_id or _content_changed(old_by_id[ident], products[ident])
            ) else photos.get(url)
            if src is None:
                # A newly approved row may cite an unchanged, previously
                # approved media file that the new publisher didn't copy.
                src = photos.get(url)
            if src is None or hashlib.sha256(src.read_bytes()).hexdigest() != expected:
                raise CatalogRefreshError("Verified approved public photograph is unavailable")
            required_images[url] = src

    ordered = sorted(
        products.values(),
        key=lambda item: (
            item["manufacturer"].casefold(), item["model"].casefold(), item["id"]
        ),
    )
    reject_held_products(ordered, provenance, holds)
    version = "r" + secrets.token_hex(10)
    now = datetime.now(timezone.utc).isoformat()
    index = {
        "schema": RELEASE_SCHEMA, "version": version, "as_of": now,
        "coverage": {
            "description": "Only expressly approved Area 33 listings; not live stock or full distributor coverage."
        },
        "total": len(ordered), "shards": [], "products": [],
    }
    written_shards = []
    for part_no, offset in enumerate(range(0, len(ordered), PER_SHARD), 1):
        page = ordered[offset:offset + PER_SHARD]
        name = f"assets/catalog-shards/{version}/part-{part_no:04d}.json"
        body = _encode({"schema": SHARD_SCHEMA, "version": version, "items": page})
        index["shards"].append({
            "url": name, "sha256": hashlib.sha256(body).hexdigest(),
            "count": len(page),
        })
        written_shards.append((name, body))
        for row in page:
            index["products"].append({
                "id": row["id"], "manufacturer": row["manufacturer"],
                "model": row["model"], "variant": row["variant"],
                "description": row["description"], "category": row["category"],
                "product_type": row["product_type"], "shard": part_no - 1,
            })
    audit = {
        "schema": "area33.catalog.private_release_audit.v1",
        "release_kind": "approved_refresh",
        "version": version, "created_at": now,
        "owner_approved_public_record_count": len(ordered),
        "source_approved_bundle_count": len(bundles),
        "previous_version": prior_index["version"],
        "previous_snapshot_verified": True,
        "unchanged_previously_approved_records": previously_approved_unchanged,
        "new_independently_approved_records": added,
        "independently_reapproved_changed_records": independently_reapproved_changed,
        "new_bundles_with_unchanged_content": refreshed_unchanged,
        "previous_catalog_record_count": len(old_by_id),
        "approved_withdrawal_count": len(withdraw),
        "approved_withdrawals": list(withdraw.values()),
        "private_rights_holds_sha256": holds["sha256"],
        "private_rights_holds_count": holds["hold_count"],
        "private_source_media_file_count": len(required_images),
        "published": False, "website_modified": False,
        "note": "PRIVATE refreshed approved-only snapshot. No new product approvals inferred and no deployment.",
    }
    output.parent.mkdir(parents=True,exist_ok=True)
    temporary = Path(tempfile.mkdtemp(prefix=".area33-refresh-", dir=output.parent))
    try:
        for name, body in written_shards:
            path = temporary.joinpath(*Path(name).parts)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
        for name, source in sorted(required_images.items()):
            target = temporary.joinpath(*Path(name).parts)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
            if hashlib.sha256(source.read_bytes()).digest() != hashlib.sha256(
                target.read_bytes()
            ).digest():
                raise CatalogRefreshError("Approved image changed in refresh copy")
        dest = temporary/"assets/catalog-index.v2.json"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(_encode(index))
        (temporary/"catalog-private-release-audit.json").write_bytes(_encode(audit))
        (temporary/"catalog-private-media-provenance.json").write_bytes(
            _encode({
                "schema": "area33.catalog.private_media_provenance.v1",
                "release_version": version,
                "public_catalog_record_count": len(ordered),
                "records": sorted(provenance.values(), key=lambda row: row["id"]),
                "notice": "PRIVATE original image hashes and owner rights evidence, not a public file.",
            })
        )
        (temporary/"READ_ME_FIRST.txt").write_text(
            "PRIVATE approved-only refresh. No new permission inferred. "
            "Do not upload without independent owner deployment authorization.\n",
            encoding="utf-8",
        )
        temporary.rename(output)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
    return audit, index


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--previous-private-release", type=Path, required=True)
    p.add_argument("--approved-bundle", type=Path, action="append", default=[])
    p.add_argument("--reviewed-withdrawals", type=Path)
    p.add_argument("--rights-holds", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--stage-private-refresh", action="store_true")
    args = p.parse_args(argv)
    if not args.stage_private_refresh:
        p.error("Explicit --stage-private-refresh required")
    try:
        audit, index = refresh_approved_catalog(
            args.previous_private_release, args.out,
            approved_bundles=args.approved_bundle,
            reviewed_withdrawals=args.reviewed_withdrawals,
            rights_holds_file=args.rights_holds,
        )
    except (OSError, ValueError, KeyError, TypeError) as exc:
        p.error(str(exc))
    print("PRIVATE approved-only catalog refresh staged; NOT published.")
    print("  Previously approved retained unchanged:", audit["unchanged_previously_approved_records"])
    print("  Newly approved records:", audit["new_independently_approved_records"])
    print("  Updated separately reapproved records:", audit["independently_reapproved_changed_records"])
    print("  Reviewed withdrawals:", audit["approved_withdrawal_count"])
    print("  Approved catalog count:", index["total"])
    print("  Private output:", args.out)


if __name__ == "__main__":
    main()
