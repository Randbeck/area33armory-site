import assert from "node:assert/strict";
import fs from "node:fs";
const read = p => fs.readFileSync(new URL("../" + p, import.meta.url), "utf8");
const home = read("index.html");
const portfolio = read("portfolio.html");
const ffl = read("ffl-finder.html");
const studio = read("studio.html");
const browser = read("assets/public-directories.js");
assert.match(home, /href="studio\.html"/);
assert.match(home, /href="portfolio\.html"/);
assert.match(home, /href="ffl-finder\.html"/);
assert.match(portfolio, /data-directory="portfolio"/);
assert.match(ffl, /data-directory="ffl"/);
assert.match(studio, /id="optic-compact"/);
assert.match(studio, /id="muzzle-cylinder"/);
assert.match(browser, /credentials:"omit"/);
assert.doesNotMatch(browser, /localStorage|sessionStorage|Authorization:/);
const portfolios=JSON.parse(read("assets/passport-public.json"));
const partners=JSON.parse(read("assets/ffl-public.json"));
assert.equal(portfolios.schema, "passport.public.v1");
assert.equal(partners.schema, "ffl.partners.public.v1");
assert.deepEqual(portfolios.items, []);
assert.deepEqual(partners.items, []);
const contact = read("contact.html");
const catalog = read("assets/catalog.js");
assert.match(contact,/Image or trademark rights/);
assert.match(contact,/\^catalog_\[a-f0-9\]\{20\}\$/);
assert.match(catalog,/Report an image or attribution concern/);
assert.match(catalog,/encodeURIComponent\(item\.id\)/);
assert.doesNotMatch(contact,/fetch\(|sendBeacon\(/);
console.log("Area 33 draft site: routes, schemas, rights contact, and zero private data verified.");
