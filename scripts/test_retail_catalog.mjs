import assert from "node:assert/strict";
import fs from "node:fs";
import {REFERENCE_PRODUCTS} from "../assets/product-room-research.mjs";
import {researchPhotoFor} from "../assets/research-photo-license.mjs";
import {findResearchProducts} from "../assets/customer-experience.mjs";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
const html=read("catalog.html");
const js=read("assets/catalog-research.js");
const css=read("assets/catalog-research.css");
const home=read("index.html");
const retail=read("assets/retail-finish.css");
const approved=JSON.parse(read("assets/catalog-public.json"));
assert.deepEqual(approved.items,[],"Do not invent published inventory");
assert.match(html,/Find something <em>worth exploring/);
assert.match(html,/id="research-catalog-grid"/);
assert.match(html,/id="research-catalog-search"/);
assert.match(html,/id="research-catalog-type"/);
assert.match(html,/id="research-catalog-dialog"/);
assert.match(html,/id="research-catalog-detail"/);
assert.match(html,/type="module" src="assets\/catalog-research\.js"/);
assert.match(html,/type="module" src="assets\/catalog\.js"/,"Approved catalog preserved");
assert.match(html,/href="index\.html\?inspect=glock-g19-gen5-mos&amp;eva=1"/);
assert.doesNotMatch(html,/<nav aria-label="Primary">[\s\S]*?experience-lab\.html/,"Catalog should not route users into Experience Lab");
const gallery=html.indexOf('id="research-catalog-grid"'),approvedArea=html.indexOf('class="shell workspace"');
assert.ok(gallery>=0&&approvedArea>gallery,"Real research models must be browsable before empty approved-catalog feed");
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size);
const firearms=REFERENCE_PRODUCTS.filter(x=>x.kind==="firearm");
assert.ok(firearms.length>=8);
assert.equal(findResearchProducts("","all").length,firearms.length,"Research results never truncated to 3");
assert.equal(findResearchProducts("precision","rifles").every(x=>x.department==="rifles"),true);
assert.equal(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="glock-g19-gen5-mos")),null,"No fake Glock photo");
assert.ok(researchPhotoFor(REFERENCE_PRODUCTS.find(x=>x.id==="ruger-precision-308-gen1")));
assert.match(js,/researchPhotoFor\(product\)/);
assert.match(js,/findResearchProducts\(query,category,all\)/);
assert.match(js,/dialog\.showModal\(\)/);
assert.match(js,/dialog\?\.addEventListener\("click"/);
assert.match(js,/index\.html\?inspect=/);
assert.match(js,/encodeURIComponent\(product\.id\)/);
assert.match(js,/Price and availability not verified/);
assert.doesNotMatch(js,/localStorage|sessionStorage|Authorization|dealer[_-]?cost|supplier[_-]?token|private[_-]?source/);
assert.match(css,/\.research-catalog-grid\{/);
assert.match(css,/\.research-catalog-dialog\{/);
assert.match(css,/@media\(max-width:650px\)/);
assert.match(home,/assets\/retail-finish\.css/);
assert.match(retail,/--retail-red:/);
assert.match(retail,/\.department-grid/);
assert.match(home,/Find your next/);
assert.ok((home.match(/class="department-emblem"/g)||[]).length===6);
assert.match(home,/Browse the catalog/);
console.log("Area 33: Catalog is directly browsable with licensed exact-item research, existing approved catalog intact, premium retail presentation and EVA deep links.");
